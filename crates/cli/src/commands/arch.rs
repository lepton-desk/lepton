//! The Arch Linux package (`.pkg.tar.zst`), written in Rust with no `makepkg`.
//!
//! A pacman package is a tar archive whose first members describe it: `.MTREE` (a gzipped
//! list of every file with its mode, size and SHA-256, which `pacman -Qkk` checks an
//! install against) and `.PKGINFO` (name, version, size, dependencies). The rest is the
//! bundle tree under `usr/` — the binary resolves its frontend from
//! `<exe>/../share/<name>/dist`, so `/usr/bin` + `/usr/share` is the same layout the
//! bundle directory already has. Dependencies come from the binary's own `DT_NEEDED`
//! list (`depends.rs`), never from a hand-kept table.
//!
//! Compression is `ruzstd`'s pure-Rust encoder at its fastest level (about `zstd -1`); the
//! stronger levels are not implemented there yet. Like every Lepton archive the result is
//! reproducible: sorted entries, `root:root`, one time stamp.

use std::fmt::Write as _;
use std::io::Write as _;
use std::path::{Path, PathBuf};

use sha2::Digest as _;

use super::CliError;
use super::archive::{self, io};

/// What one Arch package is made of.
pub struct Package<'a> {
    /// The bundle directory (`bin/`, `share/`).
    pub bundle: &'a Path,
    /// Names in the bundle directory that are not shipped.
    pub skip: &'a [&'a str],
    /// The package name: the executable's name, already lowercase `[a-z0-9_-]`.
    pub name: &'a str,
    pub version: &'a str,
    pub description: &'a str,
    /// `bundle.homepage`, `bundle.license` (SPDX, as Arch writes licenses since 2023).
    pub url: Option<&'a str>,
    pub license: Option<&'a str>,
    /// Package names the binary needs, sorted.
    pub depends: &'a [String],
    pub mtime: u64,
    /// The directory the package is written to.
    pub out: &'a Path,
}

/// A semver version as a `pkgver`, which allows no `-` (it separates `pkgrel`), `:` or `/`.
///
/// The pre-release dash is dropped, not replaced: measured with `vercmp`, `1.0.0beta.1`
/// sorts before `1.0.0` (as semver wants) while `1.0.0_beta.1` and `1.0.0.beta.1` sort
/// after it, so an upgrade from a beta to the release would look like a downgrade. Build
/// metadata (`+…`) carries no precedence in semver and is left out.
pub fn pkgver(version: &str) -> String {
    let core = version.split('+').next().unwrap_or(version);
    let joined = core.replacen('-', "", 1);
    joined
        .chars()
        .map(|ch| {
            if ch.is_ascii_alphanumeric() || matches!(ch, '.' | '_') {
                ch
            } else {
                '.'
            }
        })
        .collect()
}

/// `<name>-<pkgver>-1-<arch>.pkg.tar.zst`.
pub fn file_name(name: &str, version: &str) -> String {
    format!(
        "{name}-{}-1-{}.pkg.tar.zst",
        pkgver(version),
        std::env::consts::ARCH
    )
}

/// Writes the package and returns its path and SHA-256.
pub fn write(package: &Package<'_>) -> Result<(PathBuf, String), CliError> {
    let out = package.out.join(file_name(package.name, package.version));
    archive::refuse_foreign(&out)?;

    let mut entries = vec![archive::Entry {
        path: PathBuf::from("usr"),
        source: package.bundle.to_path_buf(),
        directory: true,
        executable: false,
    }];
    entries.extend(archive::sorted_entries(
        package.bundle,
        Path::new("usr"),
        package.skip,
    )?);

    let installed: u64 = entries
        .iter()
        .filter(|entry| !entry.directory)
        .map(|entry| std::fs::metadata(&entry.source).map(|meta| meta.len()))
        .sum::<Result<u64, _>>()
        .map_err(|error| io(package.bundle, "inspect", &error))?;

    let pkginfo = pkginfo(package, installed);
    let mtree = mtree(&entries, &pkginfo, package.mtime)?;

    let mut builder = tar::Builder::new(Vec::new());
    for (name, bytes) in [
        (".MTREE", mtree.as_slice()),
        (".PKGINFO", pkginfo.as_bytes()),
    ] {
        let mut head = archive::header(false, false, bytes.len() as u64, package.mtime);
        builder
            .append_data(&mut head, name, bytes)
            .map_err(|error| io(&out, "write", &error))?;
    }
    archive::append_entries(&mut builder, &entries, package.mtime, &out)?;
    let tar = builder
        .into_inner()
        .map_err(|error| io(&out, "write", &error))?;

    let compressed = ruzstd::encoding::compress_to_vec(
        tar.as_slice(),
        ruzstd::encoding::CompressionLevel::Fastest,
    );
    let partial = out.with_extension("part");
    let mut file =
        std::fs::File::create(&partial).map_err(|error| io(&partial, "create", &error))?;
    file.write_all(&compressed)
        .and_then(|()| file.flush())
        .map_err(|error| io(&partial, "write", &error))?;
    drop(file);
    let digest = archive::publish(&partial, &out)?;
    Ok((out, digest))
}

/// The `.PKGINFO` text pacman reads first.
pub fn pkginfo(package: &Package<'_>, installed: u64) -> String {
    let mut text = String::from("# Generated by lepton package\n");
    let _ = writeln!(text, "pkgname = {}", package.name);
    let _ = writeln!(text, "pkgbase = {}", package.name);
    let _ = writeln!(text, "pkgver = {}-1", pkgver(package.version));
    let _ = writeln!(text, "pkgdesc = {}", one_line(package.description));
    if let Some(url) = package.url {
        let _ = writeln!(text, "url = {}", one_line(url));
    }
    if let Some(license) = package.license {
        let _ = writeln!(text, "license = {}", one_line(license));
    }
    let _ = writeln!(text, "builddate = {}", package.mtime);
    let _ = writeln!(text, "packager = Lepton");
    let _ = writeln!(text, "size = {installed}");
    let _ = writeln!(text, "arch = {}", std::env::consts::ARCH);
    for dependency in package.depends {
        let _ = writeln!(text, "depend = {dependency}");
    }
    text
}

/// The gzipped mtree pacman verifies an install against (`pacman -Qkk`).
fn mtree(entries: &[archive::Entry], pkginfo: &str, mtime: u64) -> Result<Vec<u8>, CliError> {
    let mut text = String::from("#mtree\n/set type=file uid=0 gid=0 mode=644\n");
    let _ = writeln!(
        text,
        "./.PKGINFO time={mtime}.0 size={} sha256digest={}",
        pkginfo.len(),
        hex(&sha2::Sha256::digest(pkginfo.as_bytes()))
    );
    for entry in entries {
        let path = escape(&entry.path.to_string_lossy());
        if entry.directory {
            let _ = writeln!(text, "./{path} time={mtime}.0 mode=755 type=dir");
        } else {
            let size = std::fs::metadata(&entry.source)
                .map_err(|error| io(&entry.source, "inspect", &error))?
                .len();
            let digest = archive::sha256_file(&entry.source)?;
            let mode = if entry.executable { " mode=755" } else { "" };
            let _ = writeln!(
                text,
                "./{path} time={mtime}.0{mode} size={size} sha256digest={digest}"
            );
        }
    }
    let mut gzip = flate2::GzBuilder::new().write(Vec::new(), flate2::Compression::best());
    gzip.write_all(text.as_bytes())
        .map_err(|error| io(Path::new(".MTREE"), "write", &error))?;
    gzip.finish()
        .map_err(|error| io(Path::new(".MTREE"), "write", &error))
}

/// mtree's encoding: anything but visible ASCII (and `\` / `#`) as a 3-digit octal escape.
fn escape(path: &str) -> String {
    let mut out = String::with_capacity(path.len());
    for byte in path.bytes() {
        if byte.is_ascii_graphic() && byte != b'\\' && byte != b'#' {
            out.push(char::from(byte));
        } else {
            let _ = write!(out, "\\{byte:03o}");
        }
    }
    out
}

fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

// The tests set Unix file modes; packaging runs on Linux only (`package.rs`).
#[cfg(all(test, unix))]
mod tests {
    use super::{Package, escape, file_name, pkgver, write};
    use lepton_orchestrator::testing::{Failure, Scratch, fail};
    use lepton_orchestrator::{assert_contains, assert_eq, assert_ok, ensure};
    use std::io::Read as _;
    use std::os::unix::fs::PermissionsExt as _;

    fn bundle(scratch: &Scratch) -> Result<(), Failure> {
        scratch.write("b/bin/notes", "#!/bin/sh\n")?;
        std::fs::set_permissions(
            scratch.path().join("b/bin/notes"),
            std::fs::Permissions::from_mode(0o755),
        )
        .map_err(|error| fail("chmod", error))?;
        scratch.write("b/share/notes/dist/index.html", "<!doctype html>\n")?;
        scratch.write(
            "b/share/applications/dev.example.notes.desktop",
            "[Desktop Entry]\n",
        )?;
        scratch.write("b/.lepton-package", "marker\n")
    }

    fn package<'a>(scratch: &'a Scratch, depends: &'a [String]) -> Package<'a> {
        Package {
            bundle: Box::leak(scratch.path().join("b").into_boxed_path()),
            skip: &[".lepton-package"],
            name: "notes",
            version: "1.2.0-beta.1",
            description: "Notes\n  app",
            url: Some("https://example.org/notes"),
            license: Some("MIT"),
            depends,
            mtime: 0,
            out: scratch.path(),
        }
    }

    /// (name, mode, contents) of every member, after zstd and tar.
    fn members(path: &std::path::Path) -> Result<Vec<(String, u32, Vec<u8>)>, Failure> {
        let file = std::fs::File::open(path).map_err(|error| fail("open", error))?;
        let decoder =
            ruzstd::decoding::StreamingDecoder::new(file).map_err(|error| fail("zstd", error))?;
        let mut archive = tar::Archive::new(decoder);
        let mut out = Vec::new();
        for entry in archive.entries().map_err(|error| fail("entries", error))? {
            let mut entry = entry.map_err(|error| fail("entry", error))?;
            let name = entry
                .path()
                .map_err(|error| fail("path", error))?
                .to_string_lossy()
                .into_owned();
            let mode = entry.header().mode().map_err(|error| fail("mode", error))?;
            let mut bytes = Vec::new();
            entry
                .read_to_end(&mut bytes)
                .map_err(|error| fail("read", error))?;
            out.push((name, mode, bytes));
        }
        Ok(out)
    }

    #[test]
    fn versions_and_names_follow_pacman_rules() -> Result<(), Failure> {
        assert_eq!(pkgver("1.2.0-beta.1"), "1.2.0beta.1");
        assert_eq!(pkgver("1.2.0+build.7"), "1.2.0");
        assert_eq!(pkgver("2:1.0/x"), "2.1.0.x");
        assert_contains!(&file_name("notes", "0.1.0"), "notes-0.1.0-1-");
        assert_eq!(escape("a b#c"), "a\\040b\\043c");
        Ok(())
    }

    #[test]
    fn metadata_comes_first_and_files_live_under_usr() -> Result<(), Failure> {
        let scratch = Scratch::new("arch-members")?;
        bundle(&scratch)?;
        let depends = [String::from("glibc"), String::from("wayland")];
        let (path, _) = assert_ok!(write(&package(&scratch, &depends)), "writes");
        let members = members(&path)?;
        let names: Vec<&str> = members.iter().map(|member| member.0.as_str()).collect();
        assert_eq!(
            names,
            vec![
                ".MTREE",
                ".PKGINFO",
                "usr/",
                "usr/bin/",
                "usr/bin/notes",
                "usr/share/",
                "usr/share/applications/",
                "usr/share/applications/dev.example.notes.desktop",
                "usr/share/notes/",
                "usr/share/notes/dist/",
                "usr/share/notes/dist/index.html",
            ]
        );
        let info = members
            .iter()
            .find(|member| member.0 == ".PKGINFO")
            .map(|member| String::from_utf8_lossy(&member.2).into_owned())
            .unwrap_or_default();
        assert_contains!(&info, "pkgver = 1.2.0beta.1-1\n");
        assert_contains!(&info, "pkgdesc = Notes app\n");
        assert_contains!(&info, "url = https://example.org/notes\n");
        assert_contains!(&info, "license = MIT\n");
        assert_contains!(&info, "depend = glibc\ndepend = wayland\n");
        // bin/notes (10 B) + index.html (16 B) + desktop entry (16 B).
        assert_contains!(&info, "size = 42\n");
        let binary = members.iter().find(|member| member.0 == "usr/bin/notes");
        ensure!(
            binary.is_some_and(|member| member.1 == 0o755),
            "binary mode"
        );
        Ok(())
    }

    #[test]
    fn two_writes_are_byte_identical() -> Result<(), Failure> {
        let scratch = Scratch::new("arch-repro")?;
        bundle(&scratch)?;
        let (_, first) = assert_ok!(write(&package(&scratch, &[])), "first");
        let (_, second) = assert_ok!(write(&package(&scratch, &[])), "second");
        assert_eq!(first, second);
        Ok(())
    }

    /// pacman itself reads the package: the strongest check short of installing it.
    #[test]
    fn pacman_reads_name_version_and_depends() -> Result<(), Failure> {
        if !std::path::Path::new("/usr/bin/pacman").exists() {
            return Ok(());
        }
        let scratch = Scratch::new("arch-pacman")?;
        bundle(&scratch)?;
        let depends = [String::from("glibc")];
        let (path, _) = assert_ok!(write(&package(&scratch, &depends)), "writes");
        let output = std::process::Command::new("pacman")
            .args(["-Qip"])
            .arg(&path)
            .env("LC_ALL", "C")
            .output()
            .map_err(|error| fail("pacman", error))?;
        let text = String::from_utf8_lossy(&output.stdout);
        ensure!(output.status.success(), "pacman -Qip failed: {text}");
        assert_contains!(&text, "notes");
        assert_contains!(&text, "1.2.0beta.1-1");
        assert_contains!(&text, "glibc");
        Ok(())
    }
}
